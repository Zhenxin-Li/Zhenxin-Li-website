# Synthetic markup is a parser test fixture, NOT financial observations.
args <- commandArgs(trailingOnly=TRUE)
if(length(args)!=1) stop("Usage: Rscript scripts/verify_parser.R path/to/blog2")
source(file.path(args[1],"scripts","parse_saved_html.R"))
fixture <- function(rows) paste0('<html><table><tr><th>Ticker</th><th>Inst Own</th></tr>',rows,'</table></html>')
p <- tempfile(fileext=".html")
writeLines(fixture('<tr><td>ABC</td><td>55.0%</td></tr>'),p)
x <- parse_saved_html(p)
stopifnot(x$Ticker=="ABC",x[['Inst Own']]=="55.0%")
writeLines(fixture('<tr><td>12</td><td>55.0%</td></tr>'),p)
stopifnot(inherits(try(parse_saved_html(p),silent=TRUE),"try-error"))
writeLines(fixture('<tr><td>ABC</td><td>55.0%</td></tr><tr><td>ABC</td><td>55.0%</td></tr>'),p)
stopifnot(inherits(try(parse_saved_html(p),silent=TRUE),"try-error"))
unlink(p)
message("PASS: header-based rvest extraction, rejection of numeric row IDs and duplicate tickers.")
